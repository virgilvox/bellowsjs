/*
 * Writes src/engines/vocal-tables.gen.ts from the fitted source data in
 * data/vocal/ (see data/vocal/README.md for where each file came from):
 * the articulator ranges and speeds, the rest posture, the inventory of
 * the bellows phonemes, the calibrated targets per body, the body constants
 * and roofs, the formant-tuning rows and the layout lengths. Everything is
 * CHIMERA's, by Jameson Hodge (MIT,
 * https://github.com/jamesondh/chimera-vocal-synth at 1d3ea49), or measured
 * on it; THIRD_PARTY_NOTICES.md says which.
 *
 * Numbers are written as decimals rounded to 7 significant digits. The
 * output depends only on the data files, so a run on any machine writes the
 * same bytes.
 *
 *   node scripts/gen-vocal-tract.mjs          write the table
 *   node scripts/gen-vocal-tract.mjs --check  exit 1 if the table is stale
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const pkg = join(here, '..');
const data = join(pkg, 'data', 'vocal');
const target = join(pkg, 'src', 'engines', 'vocal-tables.gen.ts');

const read = (name) => JSON.parse(readFileSync(join(data, name), 'utf8'));
const art = read('chimera-articulation.json');
const bodies = read('bodies.json');
const tuning = read('tuning-table.json');
const layout = read('layout.json');

const BODIES = ['male', 'female', 'child'];
const ORDER = art.articulators.order;
/* The bellows phonemes, VOCAL_PHONEMES order (src/engines/vocal-phonemes.ts), with ɫ appended. */
const PHONEMES = [
  '_', 'ɑ', 'æ', 'ʌ', 'ɔ', 'ɛ', 'ɝ', 'ɪ', 'i', 'ʊ', 'u', 'e', 'o', 'a', 'ə',
  'p', 'b', 't', 'd', 'k', 'g', 'f', 'v', 'θ', 'ð', 's', 'z', 'ʃ', 'ʒ', 'h',
  'tʃ', 'dʒ', 'm', 'n', 'ŋ', 'l', 'ɹ', 'w', 'j', 'ɾ', 'ʔ', 'ɫ',
];
const VOWELS = ['ɑ', 'æ', 'ʌ', 'ɔ', 'ɛ', 'ɝ', 'ɪ', 'i', 'ʊ', 'u', 'e', 'o', 'a', 'ə'];
/* The planner's vowel keys (planner.rs:74), and the tip for a rhotic vowel. */
const VOWEL_KEYS = ['tbX', 'tbY', 'jaw', 'lipAp', 'lipProt', 'lipWidth', 'root', 'larynx', 'ttCurl'];

const num = (x) => {
  if (x === null || x === undefined || Number.isNaN(x)) return 'NaN';
  if (!Number.isFinite(x)) throw new Error(`not finite: ${x}`);
  if (x === 0) return '0';
  return String(Number(x.toPrecision(7)));
};
const list = (xs) => '[' + xs.map(num).join(', ') + ']';

/** A target row over the 17 articulators, NaN where the phoneme sets none. */
function row(targets, keys) {
  return ORDER.map((k) => (keys.includes(k) && targets[k] !== undefined ? targets[k] : NaN));
}

function vowelRow(body, ipa) {
  const vt = art.vowelTargetsByBody[body][ipa];
  if (!vt) throw new Error(`no vowel target ${body} ${ipa}`);
  const keys = [...VOWEL_KEYS];
  if ((vt.ttCurl ?? 0) > 0.05) keys.push('ttX', 'ttY');
  return row(vt, keys);
}

function consonantRow(body, ipa) {
  const ct = art.consonantTargetsByBody[body][ipa] ?? {};
  return row(ct, ORDER);
}

const MANNERS = ['silence', 'vowel', 'stop', 'fricative', 'affricate', 'nasal', 'approximant', 'lateral', 'tap', 'glottal'];
const PLACES = ['none', 'bilabial', 'labiodental', 'dental', 'alveolar', 'postalveolar', 'retroflex', 'palatal', 'velar', 'uvular', 'labial-velar', 'glottal'];

function inventory(ipa) {
  if (ipa === '_') return { manner: 'silence', voiced: false, place: 'none', dominant: [], release: -1, nasal: false, glottal: 'none' };
  if (VOWELS.includes(ipa)) return { manner: 'vowel', voiced: true, place: 'none', dominant: [], release: -1, nasal: false, glottal: 'none' };
  const d = art.inventory.find((x) => x.ipa === ipa);
  if (!d) throw new Error(`no inventory entry for ${ipa}`);
  if (!MANNERS.includes(d.manner)) throw new Error(`manner ${d.manner}`);
  if (!PLACES.includes(d.place)) throw new Error(`place ${d.place}`);
  return {
    manner: d.manner,
    voiced: d.voicing === 'voiced',
    place: d.place,
    dominant: d.dominant,
    release: d.release ? PHONEMES.indexOf(d.release) : -1,
    nasal: !!d.nasal,
    glottal: d.glottal ?? 'none',
  };
}

const out = [];
const w = (s) => out.push(s);
w('/* Generated by scripts/gen-vocal-tract.mjs from data/vocal/. Do not edit by hand. */');
w('/*');
w(' * CHIMERA\'s articulatory data and body constants, by Jameson Hodge (MIT,');
w(' * https://github.com/jamesondh/chimera-vocal-synth at 1d3ea49).');
w(' * See data/vocal/README.md and THIRD_PARTY_NOTICES.md.');
w(' */');
w('// prettier-ignore');
w('');
w(`/** CHIMERA's 17 articulators (anatomy/human.rs:24), in this order. */`);
w(`export const VOCAL_ARTICULATOR_NAMES = ${JSON.stringify(ORDER)} as const;`);
const specs = ORDER.map((k) => art.articulators.specs.find((s) => s.key === k));
w(`/** Range and natural frequency in Hz of each articulator (control/articulators.rs:23). */`);
w(`export const VOCAL_ARTICULATOR_MIN: readonly number[] = ${list(specs.map((s) => s.min))};`);
w(`export const VOCAL_ARTICULATOR_MAX: readonly number[] = ${list(specs.map((s) => s.max))};`);
w(`export const VOCAL_ARTICULATOR_HZ: readonly number[] = ${list(specs.map((s) => s.hz))};`);
w(`/** CHIMERA's NEUTRAL posture, the performer's rest (anatomy/human.rs). */`);
w(`export const VOCAL_NEUTRAL: readonly number[] = ${list(ORDER.map((k) => art.neutral[k] ?? art.restPosture[k]))};`);
w('');
w(`/** The phonemes the tables describe: VOCAL_PHONEMES order, then the velarized lateral. */`);
w(`export const VOCAL_TABLE_PHONEMES = ${JSON.stringify(PHONEMES)} as const;`);
w(`export const VOCAL_MANNERS = ${JSON.stringify(MANNERS)} as const;`);
w(`export const VOCAL_PLACES = ${JSON.stringify(PLACES)} as const;`);
w('');
w('export interface VocalInventoryRow {');
w('  manner: (typeof VOCAL_MANNERS)[number];');
w('  voiced: boolean;');
w('  place: (typeof VOCAL_PLACES)[number];');
w('  /** Indices into VOCAL_ARTICULATOR_NAMES of the articulators the sound dominates. */');
w('  dominant: readonly number[];');
w('  /** Index into VOCAL_TABLE_PHONEMES of an affricate\'s release fricative, or -1. */');
w('  release: number;');
w('  nasal: boolean;');
w("  glottal: 'none' | 'open' | 'stop' | 'breathy';");
w('}');
w('');
w(`/** CHIMERA's inventory for each phoneme (phonetics/inventory.rs). */`);
w('export const VOCAL_INVENTORY: readonly VocalInventoryRow[] = [');
for (const ipa of PHONEMES) {
  const d = inventory(ipa);
  w(`  { manner: '${d.manner}', voiced: ${d.voiced}, place: '${d.place}', dominant: [${d.dominant.map((k) => ORDER.indexOf(k)).join(', ')}], release: ${d.release}, nasal: ${d.nasal}, glottal: '${d.glottal}' }, // ${ipa}`);
}
w('];');
w('');
w('export interface VocalBodyTable {');
w('  name: string;');
w('  /** CHIMERA HumanBody.scale and its pharynx factor. */');
w('  k: number;');
w('  pharynxScale: number;');
w('  tongueRadius: number;');
w('  lipWidthBody: number;');
w('  /** The roof polyline, body cm: the velum from the uvula tip, then the hard palate to the incisors. */');
w('  roofX: readonly number[];');
w('  roofY: readonly number[];');
w('  /** Shortest glottis-to-lips length any frame needs, and the neutral posture\'s pharynx and total length, cm. */');
w('  minLength: number;');
w('  neutralPharynx: number;');
w('  neutralLength: number;');
w('  /** Per phoneme (VOCAL_TABLE_PHONEMES order) and articulator: the calibrated target, NaN for none. */');
w('  vowelTargets: readonly (readonly number[])[];');
w('  consonantTargets: readonly (readonly number[])[];');
w('  /** Per phoneme, vowels only (0 elsewhere): R1 Hz, its change per unit opening, the vowel\'s jaw, R1 at the largest opening. */');
w('  tuneR1: readonly number[];');
w('  tuneSlope: readonly number[];');
w('  tuneJaw: readonly number[];');
w('  tuneR1Max: readonly number[];');
w('}');
w('');
w('export const VOCAL_BODIES: readonly VocalBodyTable[] = [');
for (const body of BODIES) {
  const m = bodies.bodies[body];
  const lay = layout.bodies[body];
  if (m.k !== lay.scale) throw new Error(`scale mismatch ${body}`);
  w('  {');
  w(`    name: '${body}',`);
  w(`    k: ${num(m.k)},`);
  w(`    pharynxScale: ${num(m.pharynxScale)},`);
  w(`    tongueRadius: ${num(m.tongueRadius)},`);
  w(`    lipWidthBody: ${num(m.lipWidthBody)},`);
  w(`    roofX: ${list(m.roof.map((p) => p[0]))},`);
  w(`    roofY: ${list(m.roof.map((p) => p[1]))},`);
  w(`    minLength: ${num(lay.minLength)},`);
  w(`    neutralPharynx: ${num(lay.neutralPharynx)},`);
  w(`    neutralLength: ${num(lay.neutralLength)},`);
  w('    vowelTargets: [');
  for (const ipa of PHONEMES) w(`      ${list(VOWELS.includes(ipa) ? vowelRow(body, ipa) : ORDER.map(() => NaN))}, // ${ipa}`);
  w('    ],');
  w('    consonantTargets: [');
  for (const ipa of PHONEMES) {
    const isC = !VOWELS.includes(ipa) && ipa !== '_';
    w(`      ${list(isC ? consonantRow(body, ipa) : ORDER.map(() => NaN))}, // ${ipa}`);
  }
  w('    ],');
  const tr = (f) => PHONEMES.map((p) => (VOWELS.includes(p) ? f(tuning[body][p]) : 0));
  w(`    tuneR1: ${list(tr((r) => r.r1))},`);
  w(`    tuneSlope: ${list(tr((r) => r.slope))},`);
  w(`    tuneJaw: ${list(tr((r) => r.jaw))},`);
  w(`    tuneR1Max: ${list(tr((r) => r.r1max))},`);
  w('  },');
}
w('];');
w('');
const text = out.join('\n');

if (process.argv.includes('--check')) {
  let old = '';
  try {
    old = readFileSync(target, 'utf8');
  } catch {
    /* missing counts as stale */
  }
  if (old !== text) {
    console.error('src/engines/vocal-tables.gen.ts is stale: run npm run gen:vocal -w packages/bellows');
    process.exit(1);
  }
  console.log(`vocal tables: up to date (${(text.length / 1024).toFixed(1)} KB)`);
} else {
  writeFileSync(target, text);
  console.log(`vocal tables: ${(text.length / 1024).toFixed(1)} KB`);
}
