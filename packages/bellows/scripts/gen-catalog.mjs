/*
 * Writes src/core/catalog.gen.ts: every built-in engine's and effect's id, label, params and
 * polyphony, read from the real definitions after registerBuiltins(), in its order. The main thread
 * lists engines from this table so it need not import their DSP. --check fails if the file is stale;
 * test/integration/catalog.test.ts checks the same thing on every test run.
 */
import { build } from 'esbuild';
import { readFileSync, writeFileSync, mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const pkg = join(here, '..');
const dir = mkdtempSync(join(tmpdir(), 'bellows-catalog-'));
const outfile = join(dir, 'catalog.mjs');
try {
  await build({
    stdin: {
      contents: `import { registerBuiltins } from './src/register';
import { listEngines, listEffects } from './src/core/registry';
registerBuiltins();
export const engines = listEngines();
export const effects = listEffects();`,
      resolveDir: pkg,
      loader: 'ts',
    },
    bundle: true,
    format: 'esm',
    platform: 'node',
    outfile,
    logLevel: 'error',
  });
  const { engines, effects } = await import(pathToFileURL(outfile).href);
  const engineInfo = engines.map((e) => ({
    id: e.id,
    label: e.label,
    params: e.params,
    ...(e.polyphony !== undefined ? { polyphony: e.polyphony } : {}),
  }));
  const effectInfo = effects.map((f) => ({ id: f.id, label: f.label, params: f.params }));
  const text =
    '/* Generated by scripts/gen-catalog.mjs from registerBuiltins(). Do not edit by hand. */\n' +
    "import type { EffectInfo, EngineInfo } from '../types';\n\n" +
    '// prettier-ignore\n' +
    'export const BUILTIN_ENGINES: readonly EngineInfo[] = ' + JSON.stringify(engineInfo) + ';\n\n' +
    '// prettier-ignore\n' +
    'export const BUILTIN_EFFECTS: readonly EffectInfo[] = ' + JSON.stringify(effectInfo) + ';\n';
  const target = join(pkg, 'src/core/catalog.gen.ts');
  if (process.argv.includes('--check')) {
    let old = '';
    try {
      old = readFileSync(target, 'utf8');
    } catch {}
    if (old !== text) {
      console.error('src/core/catalog.gen.ts is stale: run npm run gen:catalog -w packages/bellows');
      process.exit(1);
    }
    console.log('catalog up to date: ' + engineInfo.length + ' engines, ' + effectInfo.length + ' effects');
  } else {
    writeFileSync(target, text);
    console.log('catalog: ' + engineInfo.length + ' engines, ' + effectInfo.length + ' effects, ' + text.length + ' bytes');
  }
} finally {
  rmSync(dir, { recursive: true, force: true });
}
