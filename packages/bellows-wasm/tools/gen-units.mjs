#!/usr/bin/env node
/*
 * The table that joins the TypeScript param names to the C++ Params fields, for the units the
 * WebAssembly module carries.
 *
 *   src/units.gen.h        per unit, a setter that writes param index i into its Params struct,
 *                          and the Unit enum the ABI dispatches on
 *   src/manifest.gen.json  per unit, its id, label, polyphony and ParamSpec list, in the same
 *                          order as the setter's indices: the JS side maps a name to an index
 *                          with it and builds the catalog entries from it
 *
 * The specs are read out of packages/bellows/dist/bellows.js after registerBuiltins(), the same
 * way bellows-embedded/tools/gen-tables.mjs reads them, so what this joins is what ships. The
 * field each name lands on is the camelCase name in snake_case unless the table below says
 * otherwise, and the compiler is the check: a name that maps to a field the C++ struct does not
 * have fails the build, not a test.
 *
 *   node tools/gen-units.mjs           write both files
 *   node tools/gen-units.mjs --check   exit 1 when either committed file is stale
 */

import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const PKG = dirname(HERE);
const REPO = dirname(dirname(PKG));
const TS_DIST = join(REPO, 'packages', 'bellows', 'dist', 'bellows.js');

/* The ported units, in the order the Unit enum numbers them. */
export const ENGINES = ['va', 'fm', 'additive', 'wavetable', 'kick', 'snare', 'hat', 'pluck', 'string', 'tube', 'modal', 'westcoast', 'formant', 'harmonic', 'clap', 'tom', 'noise'];
export const EFFECTS = ['delay', 'plate', 'compressor', 'limiter', 'gate', 'chorus', 'flanger', 'tremolo', 'autopan', 'ringmod', 'eq', 'saturator', 'transient', 'phaser', 'freqshift'];

/* Indexed TypeScript params (ratio1..ratio6) that fold into a C++ array, per unit. */
const ARRAYS = {
  fm: { ratio: 'ratio', level: 'level', fixed: 'fixed_hz' },
  additive: { partial: 'partial', target: 'target', detune: 'detune' },
};

/* Names whose C++ field is not their snake_case. */
const RENAME = {
  compressor: { threshold: 'threshold_db', knee: 'knee_db', makeup: 'makeup_db' },
  limiter: { ceiling: 'ceiling_db' },
  gate: { threshold: 'threshold_db', range: 'range_db' },
  saturator: { output: 'output_db' },
};

/* Params the ABI handles itself rather than as a field write, and why. */
const HANDLED = {
  limiter: { truePeak: 'a run time switch on the true-peak build, SetTruePeak in the ABI' },
};

const toSnake = (n) => n.replace(/([a-z0-9])([A-Z])/g, '$1_$2').toLowerCase();

function fieldOf(unit, name) {
  if (HANDLED[unit]?.[name]) return null;
  if (unit === 'eq') {
    const m = /^b(\d)(freq|gain|q|enabled)$/.exec(name);
    if (!m) throw new Error(`eq: unexpected param ${name}`);
    return `band[${m[1]}].${{ freq: 'freq', gain: 'gain_db', q: 'q', enabled: 'enabled' }[m[2]]}`;
  }
  const idx = /^([a-zA-Z]+?)(\d+)$/.exec(name);
  if (idx && ARRAYS[unit]?.[idx[1]]) return `${ARRAYS[unit][idx[1]]}[${Number(idx[2]) - 1}]`;
  return RENAME[unit]?.[name] ?? toSnake(name);
}

const ident = (id) => id.charAt(0).toUpperCase() + id.slice(1);

export async function generate() {
  if (!existsSync(TS_DIST)) throw new Error('packages/bellows/dist not found. Run: npm run build -w packages/bellows');
  const lib = await import(pathToFileURL(TS_DIST).href);
  lib.registerBuiltins();
  const engines = new Map(lib.listEngines().map((d) => [d.id, d]));
  const effects = new Map(lib.listEffects().map((d) => [d.id, d]));

  const units = [
    ...ENGINES.map((id) => ({ kind: 'engine', def: engines.get(id), id })),
    ...EFFECTS.map((id) => ({ kind: 'effect', def: effects.get(id), id })),
  ];
  for (const u of units) if (!u.def) throw new Error(`${u.kind} ${u.id} is not registered by the TypeScript library`);

  const h = [];
  h.push('/* Generated by tools/gen-units.mjs from the ParamSpec arrays in packages/bellows. Do not edit.');
  h.push(' *');
  h.push(' * One setter per unit: Set(p, i, v) writes TypeScript param i (its index in the spec list,');
  h.push(' * which src/manifest.gen.json carries) into the C++ Params struct. Put() converts the value');
  h.push(' * for the field\'s type the way the TypeScript setParam does. */');
  h.push('#pragma once');
  h.push('');
  h.push('namespace bwasm {');
  h.push('');
  h.push('enum Unit : int {');
  units.forEach((u, i) => h.push(`  kUnit${ident(u.id)} = ${i},`));
  h.push(`  kUnitCount = ${units.length},`);
  h.push('};');
  h.push(`inline constexpr int kFirstEffect = ${ENGINES.length};`);
  h.push('');
  for (const u of units) {
    const params = u.def.params;
    h.push(`/* ${u.id}: ${u.def.label}, ${params.length} params */`);
    h.push(`struct Params${ident(u.id)} {`);
    h.push(`  static constexpr int kCount = ${params.length};`);
    h.push('  template <class P>');
    h.push('  static void Set(P& p, int i, float v) {');
    h.push('    switch (i) {');
    params.forEach((p, i) => {
      const f = fieldOf(u.id, p.name);
      if (f) h.push(`      case ${i}: Put(p.${f}, v); break;  // ${p.name}`);
      else h.push(`      case ${i}: break;  // ${p.name}: ${HANDLED[u.id][p.name]}`);
    });
    h.push('      default: break;');
    h.push('    }');
    h.push('  }');
    h.push('};');
    h.push('');
  }
  h.push('}  // namespace bwasm');
  h.push('');

  const manifest = units.map((u) => ({
    id: u.id,
    kind: u.kind,
    label: u.def.label,
    ...(u.def.polyphony ? { polyphony: u.def.polyphony } : {}),
    params: u.def.params,
  }));
  return { header: h.join('\n'), manifest: JSON.stringify(manifest, null, 1) + '\n' };
}

async function main() {
  const check = process.argv.includes('--check');
  const { header, manifest } = await generate();
  let ok = true;
  for (const [rel, text] of [['src/units.gen.h', header], ['src/manifest.gen.json', manifest]]) {
    const path = join(PKG, rel);
    const old = existsSync(path) ? readFileSync(path, 'utf8') : null;
    if (old === text) continue;
    if (check) {
      process.stderr.write(`${rel} is stale\n`);
      ok = false;
    } else {
      writeFileSync(path, text);
      process.stdout.write(`wrote ${rel}\n`);
    }
  }
  if (!ok) {
    process.stderr.write('Run: node tools/gen-units.mjs\n');
    process.exit(1);
  }
}

if (process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url) {
  main().catch((e) => {
    process.stderr.write(`${e.stack || e.message}\n`);
    process.exit(2);
  });
}
